import { expect, test } from "@playwright/test";
test.use({ viewport: { width: 1280, height: 900 } });
for (const mode of ["light", "dark"]) test(`contextual errors retain details and close locally in ${mode}`, async ({ page }) => {
    await page.goto(`/browser-harness.html?reminder-presentation=1&appearance=${mode}`);
    await expect(page.locator("html")).toHaveAttribute("data-appearance", mode);
    await expect(page.locator(".reminder-floating")).toHaveCount(0);
    const notice = page.getByRole("alert").filter({ hasText: "Failed request" });
    await expect(notice).toBeVisible();
    await notice.getByRole("button", { name: "Show details", exact: true }).click();
    await expect(notice).toContainText("permission_denied");
    await expect(notice).toContainText("00000000-0000-4000-8000-000000000001");
    const position = await notice.evaluate((node) => getComputedStyle(node).position);
    expect(position).not.toBe("fixed");
    await notice.getByRole("button", { name: "Close", exact: true }).click();
    await expect(notice).toHaveCount(0);
    await expect(page.getByLabel("Failure state", { exact: true })).toHaveText("true");
    await page.getByRole("button", { name: "Render again", exact: true }).click();
    await expect(notice).toHaveCount(0);
    await page.getByRole("button", { name: "Retry failure", exact: true }).click();
    await expect(notice).toBeVisible();
});
test("modal errors stay inside their dialog without moving page feedback", async ({ page }) => {
    await page.goto("/browser-harness.html?reminder-presentation=1");
    await page.getByRole("button", { name: "Open modal", exact: true }).click();
    const modal = page.locator("md-dialog[open]");
    await modal.getByRole("button", { name: "Fail inside modal", exact: true }).click();
    await expect(modal.getByRole("alert")).toContainText("Modal failure");
    await expect(page.locator(".reminder-floating")).toHaveCount(0);
    await modal.getByRole("button", { name: "Close modal", exact: true }).click();
    await expect(page.getByRole("alert").filter({ hasText: "Failed request" })).toBeVisible();
    await expect(page.getByText("Required review information", { exact: true })).toBeVisible();
});
